"""
gemini_chat.py
==============
Gemini-powered conversational interpretation layer.

Architecture:
  Your CNN model → disease + confidence
  Grad-CAM      → visual heatmap (base64 image)
  SHAP weights  → environmental feature importance
  Weather API   → current environmental conditions
       ↓
  DiagnosisContext (structured JSON)
       ↓
  Gemini (interprets, explains — does NOT re-diagnose)
       ↓
  GeminiResponse (structured JSON)
       { diagnosis_summary, why_detected, environmental_factors,
         recommended_actions, prevention, disclaimer }

Gemini's role is strictly interpretive:
  - Your ML model decides: "What disease is likely?"
  - Grad-CAM answers: "Where did the model focus?"
  - SHAP answers: "Which env features contributed?"
  - Gemini answers: "How to explain this to a farmer and what practical steps are appropriate?"
"""

from __future__ import annotations

import base64
import json
import os
from typing import Any

# ── Fallback response used when Gemini is unavailable ────────────────────────
FALLBACK_RESPONSE: dict[str, Any] = {
    "diagnosis_summary": "",
    "why_detected": [],
    "environmental_factors": [],
    "recommended_actions": [],
    "prevention": [],
    "disclaimer": (
        "This analysis is generated by an AI model and is intended for informational "
        "purposes only. Always consult a qualified agronomist or plant pathologist "
        "before applying any treatment."
    ),
}

_GEMINI_MODEL = "gemini-2.0-flash"


def _build_structured_fallback(context: dict[str, Any]) -> dict[str, Any]:
    """
    Rule-based fallback used when Gemini is unavailable.
    Returns a response in the same GeminiResponse schema shape.
    """
    from backend.disease_info import get_disease_info, chatbot_response

    disease = context.get("predicted_class") or "Unknown Condition"
    crop = context.get("crop") or "plant"
    confidence = context.get("confidence") or 0.0
    conf_pct = round(confidence * 100, 1)
    weather = context.get("weather") or {}
    fi = context.get("feature_importance") or {}
    question = (context.get("question") or "").lower()

    info = get_disease_info(disease)

    # Build environmental factors from feature importance
    env_factors = []
    for factor, val in sorted(fi.items(), key=lambda x: -x[1]):
        env_factors.append({
            "factor": factor,
            "importance_pct": round(float(val), 1),
            "explanation": (
                f"{'High' if val > 40 else 'Moderate' if val > 20 else 'Lower'} influence "
                f"on {disease} risk based on current conditions."
            ),
        })

    # Determine recommended actions from knowledge base
    treatment_text = info.get("treatment", "Consult a local agricultural extension officer.")
    actions = [s.strip() for s in treatment_text.split(".") if s.strip()]

    prevention_text = info.get("prevention", "Monitor crops regularly.")
    prevention = [s.strip() for s in prevention_text.split(".") if s.strip()]

    why = [
        f"The AI model identified visual patterns characteristic of {disease}.",
        "Grad-CAM analysis indicates the model focused on highlighted leaf regions.",
    ]
    if env_factors:
        top = env_factors[0]["factor"]
        why.append(
            f"Environmental analysis shows {top} has the strongest contribution "
            f"to disease risk in your current conditions."
        )

    # Supplement with keyword-based chatbot knowledge if question is specific
    kb_answer = chatbot_response(question)
    if kb_answer and "default" not in kb_answer.lower():
        actions.insert(0, kb_answer)

    return {
        "diagnosis_summary": (
            f"The deep learning model has detected {disease} in your {crop} crop "
            f"with {conf_pct}% confidence. "
            f"Severity level: {info.get('severity', 'Unknown')}. "
            f"{info.get('description', '')}"
        ),
        "why_detected": why,
        "environmental_factors": env_factors,
        "recommended_actions": [a for a in actions if a],
        "prevention": [p for p in prevention if p],
        "disclaimer": FALLBACK_RESPONSE["disclaimer"],
    }


def _strip_data_url_prefix(data_url: str) -> tuple[str, str]:
    """Extract mime type and pure base64 from a data: URL."""
    if not data_url.startswith("data:"):
        return "image/jpeg", data_url
    header, _, b64 = data_url.partition(",")
    mime = header.split(";")[0].split(":")[1] if ":" in header else "image/jpeg"
    return mime, b64


def ask_gemini(context: dict[str, Any]) -> dict[str, Any]:
    """
    Send a structured DiagnosisContext to Gemini and return a GeminiResponse dict.

    Args:
        context: {
            question: str,
            crop: str,
            predicted_class: str,
            confidence: float,          # 0.0–1.0
            weather: dict,
            feature_importance: dict,   # {"Humidity": 52.1, ...}
            gradcam_image_b64: str,     # base64 data URL of Grad-CAM overlay
            disease_info: dict,         # from knowledge base
        }

    Returns:
        GeminiResponse dict or rule-based fallback.
    """
    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not api_key:
        return _build_structured_fallback(context)

    try:
        import google.generativeai as genai  # type: ignore[import]
        from google.generativeai.types import HarmCategory, HarmBlockThreshold  # type: ignore[import]
    except ImportError:
        return _build_structured_fallback(context)

    genai.configure(api_key=api_key)

    disease = context.get("predicted_class") or "Unknown Condition"
    crop = context.get("crop") or "plant"
    confidence = context.get("confidence") or 0.0
    question = context.get("question") or "What should I do?"
    weather = context.get("weather") or {}
    fi = context.get("feature_importance") or {}
    disease_info = context.get("disease_info") or {}
    gradcam_b64 = context.get("gradcam_image_b64") or ""

    # ── System instruction ────────────────────────────────────────────────────
    system_instruction = (
        "You are an Explainable Agricultural Assistance Module embedded in a plant disease "
        "detection system. A deep learning image classifier has already diagnosed the disease. "
        "Your role is STRICTLY to:\n"
        "1. Interpret the prediction and XAI outputs in farmer-friendly language.\n"
        "2. Explain which visual and environmental factors are relevant to this disease.\n"
        "3. Provide practical, actionable (but non-prescriptive) guidance.\n"
        "4. NEVER re-diagnose. NEVER prescribe specific chemical doses.\n"
        "5. Always include a disclaimer recommending professional agronomist consultation.\n"
        "You are the EXPLANATION and GUIDANCE layer only. The CNN model decided the diagnosis."
    )

    # ── Context block ─────────────────────────────────────────────────────────
    knowledge_summary = ""
    if disease_info:
        knowledge_summary = (
            f"\nKnowledge Base for {disease}:\n"
            f"  Causes: {disease_info.get('causes', 'N/A')}\n"
            f"  Favorable conditions: {disease_info.get('favorable_conditions', {})}\n"
            f"  General treatment approach: {disease_info.get('treatment', 'N/A')}\n"
            f"  Prevention: {disease_info.get('prevention', 'N/A')}\n"
        )

    context_json = {
        "crop": crop,
        "disease": disease,
        "confidence": round(confidence * 100, 1),
        "environment": {
            "temperature_c": weather.get("temperature_c"),
            "humidity_percent": weather.get("humidity_percent"),
            "rainfall_mm": weather.get("rainfall_mm"),
            "wind_kmh": weather.get("wind_kmh"),
            "condition": weather.get("condition"),
        },
        "environmental_importance": fi,
        "xai_note": (
            "Grad-CAM indicates the model focused on specific leaf regions shown in the "
            "heatmap image. This does not confirm a specific biological symptom — it shows "
            "where the model's attention was concentrated."
        ),
        "farmer_question": question,
    }

    # JSON output schema embedded directly in prompt (compatible with legacy SDK)
    json_schema_example = json.dumps({
        "diagnosis_summary": "2-3 sentence summary of the diagnosis and its significance.",
        "why_detected": [
            "Explanation of visual/image pattern the model likely detected.",
            "Note about Grad-CAM attention region.",
            "How environmental conditions align with this disease.",
        ],
        "environmental_factors": [
            {
                "factor": "Humidity",
                "importance_pct": 52.0,
                "explanation": "High humidity strongly favours disease spread.",
            },
            {
                "factor": "Rainfall",
                "importance_pct": 28.0,
                "explanation": "Recent rainfall creates wet conditions that promote infection.",
            },
        ],
        "recommended_actions": [
            "First practical action the farmer should take.",
            "Second practical action.",
            "Third practical action.",
        ],
        "prevention": [
            "First preventive measure.",
            "Second preventive measure.",
        ],
        "disclaimer": (
            "This analysis is for informational purposes only. Always consult a qualified "
            "agronomist before applying any treatment."
        ),
    }, indent=2)

    user_message = (
        f"Structured Diagnosis Context:\n{json.dumps(context_json, indent=2)}\n"
        f"{knowledge_summary}\n"
        f"Farmer's Question: {question}\n\n"
        "IMPORTANT: Respond ONLY with valid JSON matching this exact structure:\n"
        f"{json_schema_example}\n\n"
        "Fill every field with real, specific content based on the diagnosis context above. "
        "Do not re-diagnose. Interpret and explain the existing prediction."
    )

    # ── Build content parts (text + optional Grad-CAM image) ─────────────────
    parts: list[Any] = [user_message]

    if gradcam_b64:
        try:
            mime, b64_data = _strip_data_url_prefix(gradcam_b64)
            base64.b64decode(b64_data, validate=True)
            parts.append({
                "inline_data": {
                    "mime_type": mime,
                    "data": b64_data,
                }
            })
        except Exception:
            pass  # Skip image if malformed

    # ── Call Gemini (google-generativeai SDK) ────────────────────────────────────
    try:
        model = genai.GenerativeModel(
            model_name=_GEMINI_MODEL,
            system_instruction=system_instruction,
            generation_config=genai.types.GenerationConfig(
                response_mime_type="application/json",
                temperature=0.3,
                max_output_tokens=1500,
            ),
            safety_settings={
                HarmCategory.HARM_CATEGORY_HATE_SPEECH: HarmBlockThreshold.BLOCK_NONE,
                HarmCategory.HARM_CATEGORY_HARASSMENT: HarmBlockThreshold.BLOCK_NONE,
                HarmCategory.HARM_CATEGORY_DANGEROUS_CONTENT: HarmBlockThreshold.BLOCK_NONE,
                HarmCategory.HARM_CATEGORY_SEXUALLY_EXPLICIT: HarmBlockThreshold.BLOCK_NONE,
            },
        )
        response = model.generate_content(parts)
        result = json.loads(response.text)

        # Ensure all required fields exist
        result.setdefault("diagnosis_summary", "")
        result.setdefault("why_detected", [])
        result.setdefault("environmental_factors", [])
        result.setdefault("recommended_actions", [])
        result.setdefault("prevention", [])
        result.setdefault("disclaimer", FALLBACK_RESPONSE["disclaimer"])

        return result

    except Exception:
        # Graceful degradation — rule-based fallback
        return _build_structured_fallback(context)
