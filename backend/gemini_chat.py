def detect_intent(message: str) -> str:
    """
    Deterministic keyword-based intent classification.
    Returns one of the INTENT_KEYWORDS keys, or 'general'.
    """
    text = message.lower()
    for intent, keywords in INTENT_KEYWORDS.items():
        if any(kw in text for kw in keywords):
            return intent
    return "general"


# ── Helpers ───────────────────────────────────────────────────────────────────

def _strip_data_url_prefix(data_url: str) -> tuple[str, str]:
    """Extract mime type and pure base64 from a data: URL."""
    if not data_url.startswith("data:"):
        return "image/jpeg", data_url
    header, _, b64 = data_url.partition(",")
    mime = header.split(";")[0].split(":")[1] if ":" in header else "image/jpeg"
    return mime, b64


def _lang_name(code: str) -> str:
    names = {
        "en": "English",
        "hi": "Hindi (हिंदी)",
        "gu": "Gujarati (ગુજરાતી)",
        "mr": "Marathi (मराठी)",
        "ta": "Tamil (தமிழ்)",
        "te": "Telugu (తెలుగు)",
        "bn": "Bengali (বাংলা)",
        "pa": "Punjabi (ਪੰਜਾਬੀ)",
    }
    return names.get(code.lower(), "English")


def _build_image_part(b64_data_url: str) -> Any | None:
    """Convert base64 data URL to google.genai Part, or None if invalid."""
    if not b64_data_url:
        return None
    try:
        from google.genai import types
        mime, b64_data = _strip_data_url_prefix(b64_data_url)
        raw_bytes = base64.b64decode(b64_data, validate=True)
        return types.Part.from_bytes(data=raw_bytes, mime_type=mime)
    except Exception:
        return None


