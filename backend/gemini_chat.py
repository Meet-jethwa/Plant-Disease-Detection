def ask_gemini_initial(context: dict[str, Any]) -> dict[str, Any]:
    """
    Mode A — Initial diagnosis explanation.

    Args:
        context: Full DiagnosisContext dict including crop, disease, confidence,
                 top3, weather, feature_importance, gradcam_image_b64, disease_info, language.

    Returns:
        Structured GeminiResponse dict (Mode A schema) or rule-based fallback.
    """
    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not api_key:
        return _fallback_initial(context)

    try:
        from google import genai
        client = genai.Client(api_key=api_key)
    except Exception as exc:
        print(f"[gemini_chat] genai Client initialization failed: {exc}")
        return _fallback_initial(context)

    disease = context.get("predicted_class") or context.get("disease") or "Unknown Condition"
    crop = context.get("crop") or "plant"
    confidence = context.get("confidence") or 0.0
    conf_pct = round(confidence * 100, 2) if confidence <= 1.0 else round(confidence, 2)
    top3 = context.get("top3") or []
    weather = context.get("weather") or {}
    fi = context.get("feature_importance") or {}
    disease_info = context.get("disease_info") or {}
    gradcam_b64 = context.get("gradcam_image_b64") or ""
    language_code = context.get("language") or "en"
    target_lang = _lang_name(language_code)

    system_instruction = (
        f"You are an Explainable Agricultural Assistance Module. A deep learning classifier has already "
        f"diagnosed the disease. Your ONLY role is to interpret and explain.\n"
        f"IMPORTANT: Respond ENTIRELY in {target_lang}.\n"
        f"Rules:\n"
        f"1. NEVER re-diagnose or contradict the CNN prediction.\n"
        f"2. NEVER prescribe specific chemical doses.\n"
        f"3. NEVER invent SHAP values or Grad-CAM findings.\n"
        f"4. Always state that Grad-CAM shows model attention, NOT a confirmed disease map.\n"
        f"5. Distinguish model evidence from general agricultural knowledge.\n"
        f"6. Always recommend consulting a local agronomist for treatment decisions.\n"
        f"7. environmental_factors must use the SHAP importance values provided — do not recalculate.\n"
        f"   Combine SHAP and environment into ONE list (environmental_factors only)."
    )

    knowledge_block = ""
    if disease_info:
        knowledge_block = (
            f"\nDisease Knowledge Base ({disease}):\n"
            f"  Causes: {disease_info.get('causes', 'N/A')}\n"
            f"  Favorable conditions: {disease_info.get('favorable_conditions', 'N/A')}\n"
            f"  General treatment approach: {disease_info.get('treatment', 'N/A')}\n"
            f"  Prevention: {disease_info.get('prevention', 'N/A')}\n"
        )

    shap_list = [
        {"feature": k, "importance_pct": round(float(v), 1)}
        for k, v in sorted(fi.items(), key=lambda x: -x[1])
    ]

    context_block = json.dumps({
        "crop": crop,
        "disease": disease,
        "confidence_pct": conf_pct,
        "top_3_predictions": top3,
        "environment": {
            "temperature_c": weather.get("temperature_c"),
            "humidity_percent": weather.get("humidity_percent"),
            "rainfall_mm": weather.get("rainfall_mm"),
            "wind_kmh": weather.get("wind_kmh"),
            "condition": weather.get("condition"),
        },
        "shap_feature_importance": shap_list,
        "xai_note": (
            "Grad-CAM highlights where the CNN focused — not a pixel-level disease map. "
            "SHAP importance percentages are pre-computed by the backend; interpret them, do not recalculate."
        ),
    }, indent=2)

    user_message = (
        f"Diagnosis Context:\n{context_block}\n"
        f"{knowledge_block}\n"
        f"Return ONLY valid JSON matching this exact structure:\n{_MODE_A_SCHEMA}\n\n"
        f"Fill every field with real, specific content. "
        f"environmental_factors must include ALL SHAP features with their pre-computed importance_pct values."
    )

    parts: list[Any] = [user_message]
    img_part = _build_image_part(gradcam_b64)
    if img_part:
        parts.append(img_part)

    last_error = None
    for model_name in _FALLBACK_MODELS:
        try:
            from google.genai import types
            response = client.models.generate_content(
                model=model_name,
                contents=parts,
                config=types.GenerateContentConfig(
                    system_instruction=system_instruction,
                    response_mime_type="application/json",
                    temperature=0.3,
                    max_output_tokens=1800,
                ),
            )
            result = json.loads(response.text)

            # Ensure all required fields exist
            result.setdefault("diagnosis_summary", "")
            result.setdefault("why_detected", [])
            result.setdefault("visual_explanation", {"original_image_explanation": "", "gradcam_explanation": ""})
            result.setdefault("environmental_factors", [])
            result.setdefault("recommended_actions", [])
            result.setdefault("prevention", [])
            result.setdefault("follow_up_questions", [
                "What should I do now?",
                "Why was this disease detected?",
                "Can you explain the Grad-CAM heatmap?",
                "Is the weather increasing the risk?",
            ])
            result.setdefault("disclaimer", _DISCLAIMER)
            result.pop("shap_explanation", None)

            return result
        except Exception as exc:
            last_error = exc
            continue

    print(f"[gemini_chat] Initial diagnosis generation failed on all models: {last_error}")
    return _fallback_initial(context)


# ── Mode B — Focused follow-up chat ──────────────────────────────────────────

def ask_gemini_chat(context: dict[str, Any], intent: str) -> dict[str, Any]:
    """
    Mode B — Focused follow-up chat & General LLM Q&A answer.

    Args:
        context: Session context dict (crop, disease, confidence, weather,
                 feature_importance, disease_info, conversation_history, gradcam_image_b64,
                 message, language).
        intent:  Pre-detected intent string ('treatment', 'gradcam', 'shap', 'environment',
                 'prevention', 'symptoms', 'why_detected', 'severity', or 'general').

    Returns:
        { "chat_answer": str, "follow_up_questions": list[str], "intent": str }
    """
    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not api_key:
        return _fallback_chat(context, intent)

    try:
        from google import genai
        client = genai.Client(api_key=api_key)
    except Exception as exc:
        print(f"[gemini_chat] genai Client initialization failed: {exc}")
        return _fallback_chat(context, intent)

    disease = context.get("predicted_class") or context.get("disease") or ""
    crop = context.get("crop") or ""
    confidence = context.get("confidence") or 0.0
    conf_pct = round(confidence * 100, 2) if confidence <= 1.0 else round(confidence, 2)
    weather = context.get("weather") or {}
    fi = context.get("feature_importance") or {}
    disease_info = context.get("disease_info") or {}
    message = context.get("message") or context.get("question") or ""
    conversation_history = context.get("conversation_history") or []
    gradcam_b64 = context.get("gradcam_image_b64") or ""
    language_code = context.get("language") or "en"
    target_lang = _lang_name(language_code)

    has_diagnosis = bool(disease and disease != "Unknown Condition")

    # ── Build context block for this prompt ─────────────────────────────────
    intent_context_parts: list[str] = []

    if has_diagnosis:
        diagnosis_header = (
            f"ACTIVE DIAGNOSIS CONTEXT\n"
            f"Crop: {crop}\n"
            f"Disease: {disease}\n"
            f"Confidence: {conf_pct}%\n"
        )
        intent_context_parts.append(diagnosis_header)

        shap_block = "\n".join(
            f"  {k}: {round(float(v), 1)}%"
            for k, v in sorted(fi.items(), key=lambda x: -x[1])
        )

        weather_block = (
            f"  Humidity: {weather.get('humidity_percent', 'N/A')}%\n"
            f"  Temperature: {weather.get('temperature_c', 'N/A')}°C\n"
            f"  Rainfall: {weather.get('rainfall_mm', 'N/A')} mm\n"
            f"  Wind: {weather.get('wind_kmh', 'N/A')} km/h\n"
            f"  Condition: {weather.get('condition', 'N/A')}\n"
        )

        if intent in ("treatment", "severity"):
            intent_context_parts.append(f"DISEASE KNOWLEDGE\n  Treatment: {disease_info.get('treatment', 'N/A')}")
            intent_context_parts.append(f"ENVIRONMENT\n{weather_block}")
            if shap_block:
                intent_context_parts.append(f"SHAP CONTRIBUTIONS\n{shap_block}")

        elif intent == "gradcam":
            intent_context_parts.append(
                "XAI CONTEXT\n"
                "  The Grad-CAM heatmap image is attached (if available).\n"
                "  Red/orange = stronger CNN activation during prediction.\n"
                "  Yellow = moderate activation.\n"
                "  Blue = weaker contribution.\n"
                "  This shows model attention, NOT a pixel-level disease confirmation."
            )

        elif intent in ("shap", "environment"):
            intent_context_parts.append(f"ENVIRONMENT\n{weather_block}")
            if shap_block:
                intent_context_parts.append(f"SHAP CONTRIBUTIONS (pre-computed by backend)\n{shap_block}")
            intent_context_parts.append(
                "NOTE: SHAP % values show relative feature contributions to the disease risk score."
            )

        elif intent == "prevention":
            intent_context_parts.append(f"DISEASE KNOWLEDGE\n  Prevention: {disease_info.get('prevention', 'N/A')}")
            intent_context_parts.append(f"ENVIRONMENT\n{weather_block}")

        elif intent == "symptoms":
            intent_context_parts.append(f"DISEASE KNOWLEDGE\n  Description: {disease_info.get('description', 'N/A')}")
            intent_context_parts.append(f"  Causes: {disease_info.get('causes', 'N/A')}")

        elif intent == "why_detected":
            top3 = context.get("top3") or []
            top3_text = "\n".join(
                f"  {i+1}. {p.get('class','?')} — {round(p.get('confidence',0)*100,1)}%"
                for i, p in enumerate(top3)
            ) if top3 else "  N/A"
            intent_context_parts.append(f"TOP-3 MODEL PREDICTIONS\n{top3_text}")
            if shap_block:
                intent_context_parts.append(f"SHAP CONTRIBUTIONS\n{shap_block}")

        elif intent == "general":
            intent_context_parts.append(
                f"BACKGROUND DIAGNOSIS SUMMARY: Crop: {crop}, Detected Disease: {disease} ({conf_pct}% confidence).\n"
                f"Use this background context ONLY if the user's question is related to plant health, farming, or this diagnosis."
            )

    scoped_context = "\n\n".join(intent_context_parts) if intent_context_parts else "NO ACTIVE PLANT DIAGNOSIS CONTEXT (General Assistant Mode)"

    # ── Conversation history (text only, no images) ────────────────────────────
    history_text = ""
    if conversation_history:
        history_text = "\nPREVIOUS CONVERSATION (most recent last):\n"
        for entry in conversation_history[-6:]:  # last 3 exchanges
            role = entry.get("role", "user")
            content = entry.get("content", "")
            history_text += f"  {role.upper()}: {content}\n"

    system_instruction = (
        f"You are FloraAI, a versatile and intelligent AI assistant. You can answer general questions "
        f"on any subject (general knowledge, science, mathematics, programming, agriculture, everyday topics, etc.) "
        f"like a normal, full-featured LLM assistant in {target_lang}.\n\n"
        f"Guidelines:\n"
        f"1. Answer the user's question DIRECTLY, accurately, and naturally.\n"
        f"2. If active plant diagnosis context is provided AND the question is related to the plant scan, use the diagnosis details (Grad-CAM, SHAP, symptoms, treatment) to answer.\n"
        f"3. If the user's question is a general question (e.g. general knowledge, science, math, coding, casual chat, general farming), answer it like a normal LLM assistant without forcing unnecessary references to the plant diagnosis.\n"
        f"4. Never invent SHAP values or Grad-CAM findings if discussing plant diagnosis.\n"
        f"5. Maintain a helpful, respectful, and clear tone.\n"
        f"6. Use clear formatting with **bold** text and numbered lists/bullet points where helpful.\n"
        f"7. Respond ENTIRELY in {target_lang}."
    )

    user_message = (
        f"CONTEXT:\n{scoped_context}\n"
        f"{history_text}\n"
        f"USER QUESTION: {message}\n\n"
        f"Answer the user question directly and concisely."
    )

    parts: list[Any] = [user_message]

    # Attach Grad-CAM image only for gradcam intent
    if intent == "gradcam" and gradcam_b64:
        img_part = _build_image_part(gradcam_b64)
        if img_part:
            parts.append(img_part)

    follow_ups = FOLLOW_UP_BY_INTENT.get(intent, FOLLOW_UP_BY_INTENT["general"])

    last_error = None
    for model_name in _FALLBACK_MODELS:
        try:
            from google.genai import types
            response = client.models.generate_content(
                model=model_name,
                contents=parts,
                config=types.GenerateContentConfig(
                    system_instruction=system_instruction,
                    temperature=0.4,
                    max_output_tokens=800,
                ),
            )
            chat_answer = (response.text or "").strip()

            return {
                "chat_answer": chat_answer,
                "follow_up_questions": follow_ups,
                "intent": intent,
            }
        except Exception as exc:
            last_error = exc
            continue

    print(f"[gemini_chat] All Gemini models failed. Error: {last_error}")
    return _fallback_chat(context, intent)


# ── Rule-based fallbacks ──────────────────────────────────────────────────────

def _fallback_initial(context: dict[str, Any]) -> dict[str, Any]:
    """Rule-based fallback for Mode A when Gemini is unavailable."""
    from backend.disease_info import get_disease_info

    disease = context.get("predicted_class") or context.get("disease") or "Unknown Condition"
    crop = context.get("crop") or "plant"
    confidence = context.get("confidence") or 0.0
    conf_pct = round(confidence * 100, 2) if confidence <= 1.0 else round(confidence, 2)
    fi = context.get("feature_importance") or {}
    disease_info = context.get("disease_info") or get_disease_info(disease)

    env_factors = [
        {
            "factor": k,
            "importance_pct": round(float(v), 1),
            "explanation": (
                f"{'High' if v > 40 else 'Moderate' if v > 20 else 'Lower'} influence "
                f"on {disease} risk based on current conditions."
            ),
        }
        for k, v in sorted(fi.items(), key=lambda x: -x[1])
    ]

    top_factor = env_factors[0]["factor"] if env_factors else "humidity"
    treatment = disease_info.get("treatment", "Consult a local agricultural extension officer.")
    prevention = disease_info.get("prevention", "Monitor crops regularly.")
    actions = [s.strip() for s in treatment.split(".") if s.strip()][:5]
    prev_steps = [s.strip() for s in prevention.split(".") if s.strip()][:3]

    return {
        "diagnosis_summary": (
            f"The deep learning model has detected {disease} in your {crop} crop "
            f"with {conf_pct}% confidence. {disease_info.get('description', '')}"
        ),
        "why_detected": [
            f"The AI model identified visual patterns characteristic of {disease}.",
            "Grad-CAM analysis indicates the model focused on highlighted leaf regions in the heatmap image.",
            f"Environmental analysis shows {top_factor} has the strongest contribution to disease risk.",
        ],
        "visual_explanation": {
            "original_image_explanation": (
                f"The uploaded image shows your {crop} leaf. The CNN analysed visual texture, "
                f"colour distribution, and lesion patterns to produce the {disease} classification."
            ),
            "gradcam_explanation": (
                "The Grad-CAM heatmap highlights regions where the model had the strongest activation. "
                "Warmer colours (red/orange) indicate areas that most influenced the classification. "
                "This shows model attention, not a confirmed symptom map."
            ),
        },
        "environmental_factors": env_factors,
        "recommended_actions": [a for a in actions if a],
        "prevention": [p for p in prev_steps if p],
        "follow_up_questions": [
            "What should I do now?",
            "Why was this disease detected?",
            "Can you explain the Grad-CAM heatmap?",
            "Is the weather increasing the risk?",
        ],
        "disclaimer": _DISCLAIMER,
    }


def _fallback_chat(context: dict[str, Any], intent: str) -> dict[str, Any]:
    """Rule-based fallback for Mode B when Gemini is unavailable."""
    from backend.disease_info import get_disease_info

    disease = context.get("predicted_class") or context.get("disease") or "Unknown Condition"
    crop = context.get("crop") or "plant"
    confidence = context.get("confidence") or 0.0
    conf_pct = round(confidence * 100, 2) if confidence <= 1.0 else round(confidence, 2)
    fi = context.get("feature_importance") or {}
    weather = context.get("weather") or {}
    disease_info = context.get("disease_info") or get_disease_info(disease)

    if intent == "treatment":
        treatment = disease_info.get("treatment", "Consult a local agricultural extension officer.")
        answer = (
            f"Since the model detected **{disease}** with {conf_pct}% confidence, "
            f"here are the recommended steps:\n\n{treatment}\n\n"
            "Please consult a local agronomist before applying any chemical treatment."
        )

    elif intent == "gradcam":
        answer = (
            f"The Grad-CAM heatmap shows **where the CNN concentrated its visual attention** "
            f"when predicting {disease}.\n\n"
            "**Red/orange areas** indicate stronger model activation.\n"
            "**Yellow areas** indicate moderate contribution.\n"
            "**Blue areas** indicate weaker contribution.\n\n"
            "This is model attention — it does not confirm that every highlighted pixel contains the disease."
        )

    elif intent in ("shap", "environment"):
        shap_lines = "\n".join(
            f"**{k}** — {round(float(v), 1)}%"
            for k, v in sorted(fi.items(), key=lambda x: -x[1])
        )
        answer = (
            f"**SHAP contributions** show how much each environmental feature influenced "
            f"the disease risk score for {disease}:\n\n{shap_lines}\n\n"
            f"Current conditions: humidity {weather.get('humidity_percent', 'N/A')}%, "
            f"temperature {weather.get('temperature_c', 'N/A')}°C.\n\n"
            "These percentages describe relative contributions — they do not mean the factor caused that share of the disease."
        )

    elif intent == "prevention":
        prevention = disease_info.get("prevention", "Monitor crops regularly and consult a local extension officer.")
        answer = f"**Prevention measures for {disease}:**\n\n{prevention}"

    elif intent == "why_detected":
        answer = (
            f"The CNN identified visual patterns consistent with **{disease}** "
            f"and assigned **{conf_pct}% confidence** to this prediction.\n\n"
            "The Grad-CAM heatmap shows which leaf regions most influenced the classification. "
            "This is model attention — not a pixel-level biological confirmation.\n\n"
            "Environmental conditions, particularly humidity, also align with known risk factors for this disease."
        )

    else:
        msg_lower = (context.get("message") or context.get("question") or "").lower().strip()
        has_diag = bool(context.get("predicted_class") or context.get("disease"))

        if msg_lower in ("hi", "hello", "hey", "greetings", "namaste"):
            answer = (
                "Hello! I am **FloraAI**, your AI assistant for plant disease diagnosis, crop health, "
                "and general agricultural guidance. How can I help you today?"
            )
        elif not has_diag:
            answer = (
                "I am **FloraAI**, an intelligent AI assistant. You can ask me general questions about "
                "agriculture, crop management, soil health, or general topics. You can also upload a plant leaf image "
                "for AI disease diagnosis and visual heatmap analysis!"
            )
        else:
            answer = (
                f"Regarding your active scan, the model detected **{disease}** in your {crop} with {conf_pct}% confidence. "
                "Feel free to ask about treatment protocols, prevention, environmental risk factors (SHAP), "
                "or Grad-CAM visual heatmaps, as well as general farming and agricultural questions!"
            )

    follow_ups = FOLLOW_UP_BY_INTENT.get(intent, FOLLOW_UP_BY_INTENT["general"])
    return {"chat_answer": answer, "follow_up_questions": follow_ups, "intent": intent}


