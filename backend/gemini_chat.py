"""
gemini_chat.py
==============
Two-mode Gemini interpretation layer.

Mode A  — ask_gemini_initial(context)
    Called once when a new diagnosis session starts.
    Returns the full structured diagnosis explanation.

Mode B  — ask_gemini_chat(context, intent)
    Called for every follow-up question.
    Receives only the sub-context relevant to the detected intent.
    Returns { chat_answer, follow_up_questions, intent }.

Intent detection — detect_intent(message)
    Deterministic keyword matching; falls back to "general".

Architecture:
    CNN model      → disease + confidence
    Grad-CAM       → visual heatmap (base64)
    SHAP weights   → environmental feature importance
    Weather API    → current environmental conditions
         ↓
    DiagnosisContext (stored server-side by diagnosis_id)
         ↓
    Mode A → full structured JSON response (once)
    Mode B → focused plain-text answer (every follow-up)

Gemini's role is strictly interpretive:
    - ML model decides: "What disease is likely?"
    - Grad-CAM answers: "Where did the model focus?"
    - SHAP answers: "Which env features contributed?"
    - Gemini answers: "Explain this to a farmer and what steps are appropriate?"
"""

